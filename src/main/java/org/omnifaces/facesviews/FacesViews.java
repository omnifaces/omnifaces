/**
 * <p>
 * FacesViews is a mechanism to use SEO-friendly extensionless URLs in a Faces application without the need to enlist individual Facelet source files in some
 * configuration file.
 * <p>
 * By default, all URLs generated by {@link ViewHandler#getActionURL(FacesContext, String)}, which is used by among others <code>&lt;h:form&gt;</code>,
 * <code>&lt;h:link&gt;</code>, <code>&lt;h:button&gt;</code> and all extended tags, will also be extensionless. And, URLs with an extension will be
 * 301-redirected to the extensionless one.
 *
 * <h2>Usage</h2>
 *
 * <h3>Zero configuration</h3>
 * <p>
 * Put Facelets source files into <code>/WEB-INF/faces-views</code> directory. All Facelets files in this special directory will be automatically scanned as
 * extensionless URLs.
 *
 * <h3>Minimal configuration</h3>
 * <p>
 * Below is the minimal <code>web.xml</code> configuration to make all Facelets source files found in the root folder and all subdirectories of the public web
 * content (excluding <code>/WEB-INF</code>, <code>/META-INF</code> and <code>/resources</code>) available as extensionless URLs:
 *
 * <pre>
 * &lt;context-param&gt;
 *     &lt;param-name&gt;org.omnifaces.FACES_VIEWS_SCAN_PATHS&lt;/param-name&gt;
 *     &lt;param-value&gt;/*.xhtml&lt;/param-value&gt;
 * &lt;/context-param&gt;
 * </pre>
 * <p>
 * The path pattern <code>/*.xhtml</code> basically means that all files with the <code>.xhtml</code> extension from the directory <code>/</code> must be
 * scanned, including all sub directories. In case you want to scan only <code>.xhtml</code> files in the directory <code>/foo</code>, then use path pattern of
 * <code>/foo/*.xhtml</code> instead. In case you want to scan <em>all</em> files in the directory <code>/foo</code>, then use path pattern of
 * <code>/foo</code>. You can specify multiple values separated by a comma.
 *
 * <h3>MultiViews configuration</h3>
 * <p>
 * Enabling MultiViews is a matter of suffixing the path pattern with <code>/*</code>. The support was added in OmniFaces 2.5. Below is the <code>web.xml</code>
 * configuration which extends the above minimal configuration with MultiViews support:
 *
 * <pre>
 * &lt;context-param&gt;
 *     &lt;param-name&gt;org.omnifaces.FACES_VIEWS_SCAN_PATHS&lt;/param-name&gt;
 *     &lt;param-value&gt;/*.xhtml/*&lt;/param-value&gt;
 * &lt;/context-param&gt;
 * </pre>
 * <p>
 * On an example URL of <code>https://example.com/context/foo/bar/baz</code> when neither <code>/foo/bar/baz.xhtml</code> nor <code>/foo/bar.xhtml</code> exist,
 * but <code>/foo.xhtml</code> does exist, then the request will forward to <code>/foo.xhtml</code> and make the values <code>bar</code> and <code>baz</code>
 * available as injectable path parameters via <code>&#64;</code>{@link Param} in the managed bean associated with <code>/foo.xhtml</code>.
 *
 * <pre>
 *
 * &#64;Inject
 * &#64;Param(pathIndex = 0)
 * private String bar;
 *
 * &#64;Inject
 * &#64;Param(pathIndex = 1)
 * private String baz;
 * </pre>
 *
 * <h3>Dynamic routes configuration</h3>
 * <p>
 * A directory whose name is wrapped in square brackets is a dynamic route segment. It matches exactly one path segment and exposes it under the bracketed name.
 * The support was added in OmniFaces 5.5 and needs no configuration beyond the scan path above. Given the following file:
 *
 * <pre>
 * /organizations/[id]/members.xhtml
 * </pre>
 * <p>
 * a request of <code>https://example.com/context/organizations/123/members</code> will forward to it and make the value <code>123</code> available as an
 * injectable path parameter via <code>&#64;</code>{@link Param} in the managed bean associated with <code>/members.xhtml</code>.
 *
 * <pre>
 *
 * &#64;Inject
 * &#64;Param(pathName = "id")
 * private String id;
 * </pre>
 * <p>
 * A dynamic route directory needs no welcome file, but when it has one, as in <code>/organizations/[id]/index.xhtml</code> with an extensionless
 * <code>&lt;welcome-file&gt;index&lt;/welcome-file&gt;</code>, then the bare <code>/organizations/123</code> resolves to it as well. Dynamic route segments
 * nest and compose with MultiViews, so <code>/[locale]/products/[sku]/reviews.xhtml</code> answers to <code>/nl/products/12345/reviews/2</code> with
 * <code>nl</code> and <code>12345</code> available by name and <code>2</code> available as <code>&#64;Param(pathIndex = 0)</code>.
 * <p>
 * A request path is resolved by first looking for an exact match among the scanned views, then walking the dynamic route segments, and only then falling back
 * to MultiViews. A literal directory is always preferred over a dynamic one at the same level, which means a literal sibling is a value the dynamic segment can
 * never take: given <code>/organizations/[id]/members.xhtml</code> next to <code>/organizations/settings/members.xhtml</code>, an organization whose id is
 * <code>settings</code> is unreachable. An application without any bracketed directory never reaches the dynamic route resolution at all and therefore behaves
 * exactly as before.
 * <p>
 * Note that only a <em>directory</em> name is interpreted this way. A bracketed <em>file</em> name such as <code>[id].xhtml</code> is scanned literally and
 * logged as a warning, as square brackets are gen-delims per RFC 3986 which containers may refuse in a URL outright. Links to a dynamic route are rendered with
 * every segment substituted, which is why <code>&lt;o:pathParam name&gt;</code> must supply them, see {@link PathParam}.
 *
 * <h3>Advanced configuration</h3>
 * <p>
 * See <a href="package-summary.html">package documentation</a> for configuration settings as to mapping, filtering and forwarding behavior.
 *
 * <h2>PrettyFaces</h2>
 * <p>
 * Note that there is some overlap between this feature and <a href="https://ocpsoft.org/prettyfaces">PrettyFaces</a>. The difference is that FacesViews has a
 * focus on zero- or very minimal config, where PrettyFaces has a focus on very powerful mapping mechanisms, which of course need some level of configuration.
 * As such FacesViews will only focus on auto discovering views and mapping them to both <code>.xhtml</code> and to no-extension without needing to explicitly
 * declare the <code>FacesServlet</code> in <code>web.xml</code>.
 * <p>
 * Specifically, FacesViews will thus <em>not</em> become a general URL rewriting tool (e.g. one that maps path segments to parameters, or that totally changes
 * the name of the URL). For this the user is advised to look at the aforementioned <a href="https://ocpsoft.org/prettyfaces">PrettyFaces</a>.
 *
 * @author Arjan Tijms
 * @see FacesViewsResourceHandler
 * @see FacesViewsForwardingFilter
 * @see ExtensionAction
 * @see PathAction
 * @see UriExtensionRequestWrapper
 * @see ApplicationProcessor
 * @see FacesViewsViewHandler
 * @see PathParam
 */
